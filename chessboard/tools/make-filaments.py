"""Writes chessboard/filaments.js from Bambu Studio's own filament colour table.

The table is resources/profiles/BBL/filament/filaments_color_codes.json in
https://github.com/bambulab/BambuStudio: the colour code of every Bambu filament, the same
one the AMS reads off the spool's tag. Only single-colour PLA lines that print on a stock
0.4 mm nozzle and look like a solid object are kept (no gradients, no translucent, no glow).

Two adjustments, both listed in the output: the table gives the whites as #FFFFFF and the
blacks as #000000, which no plastic is. Those few are shown as they look printed, and the
official code is kept beside them.

Usage: python3 chessboard/tools/make-filaments.py filaments_color_codes.json > chessboard/filaments.js
"""
import json, sys

LINES = [  # (Bambu name, our id, finish)
    ("PLA Basic", "basic", "basic"),
    ("PLA Matte", "matte", "matte"),
    ("PLA Silk+", "silkplus", "silk"),
    ("PLA Silk", "silk", "silk"),
    ("PLA Marble", "marble", "marble"),
    ("PLA Wood", "wood", "wood"),
    ("PLA Sparkle", "sparkle", "sparkle"),
    ("PLA Metal", "metal", "metal"),
    ("PLA Galaxy", "galaxy", "galaxy"),
]
AS_PRINTED = {  # (line, name) → how it looks printed, where the code is pure white or black
    ("PLA Basic", "Jade White"): "#F2F1EC",
    ("PLA Basic", "Black"): "#1C1C1E",
    ("PLA Matte", "Ivory White"): "#EFEAE0",
    ("PLA Matte", "Charcoal"): "#2B2C2E",
    ("PLA Silk", "White"): "#F1F0EC",
    ("PLA Silk+", "White"): "#F3F1EC",
}

data = json.load(open(sys.argv[1]))["data"]
out = []
for bambu, lid, finish in LINES:
    for e in data:
        if e["fila_type"] != bambu or len(e["fila_color"]) != 1:
            continue
        name = e["fila_color_name"]["en"].strip()
        code = "#" + e["fila_color"][0].lstrip("#")[:6].upper()
        shown = AS_PRINTED.get((bambu, name), code)
        out.append(dict(id=f"{lid}:{name.lower().replace(' ', '-')}", line=lid, name=name, hex=shown,
                        **({"code": code} if shown != code else {})))

print("/* Generated by tools/make-filaments.py from Bambu Studio's filaments_color_codes.json. Do not edit by hand. */")
print("export const LINES = " + json.dumps([dict(id=l, name=b, finish=f) for b, l, f in LINES]) + ";")
print("export const FILAMENTS = [")
for f in out:
    print("  " + json.dumps(f, ensure_ascii=False) + ",")
print("];")
